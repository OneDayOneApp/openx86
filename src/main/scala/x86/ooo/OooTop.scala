package x86.ooo

import chisel3._
import x86.isa._

/** Stage-B top-level wrapper with a Stage-A compatible debug/memory interface. */
class X86OooTop extends Module {
  val io = IO(new Bundle {
    val imem = new Bundle {
      val req_valid  = Output(Bool())
      val req_addr   = Output(UInt(64.W))
      val resp_valid = Input(Bool())
      val resp_data  = Input(UInt(256.W))
    }
    val dmem = new Bundle {
      val req_valid = Output(Bool())
      val req_we    = Output(Bool())
      val req_addr  = Output(UInt(64.W))
      val req_wdata = Output(UInt(128.W))
      val req_wmask = Output(UInt(16.W))
      val req_size  = Output(UInt(5.W))
      val resp_valid = Input(Bool())
      val resp_data  = Input(UInt(128.W))
    }
    val ptw = new Bundle {
      val req_valid = Output(Bool())
      val req_addr  = Output(UInt(64.W))
      val resp_valid = Input(Bool())
      val resp_data  = Input(UInt(64.W))
    }
    val iptw = new Bundle {
      val req_valid = Output(Bool())
      val req_addr  = Output(UInt(64.W))
      val resp_valid = Input(Bool())
      val resp_data  = Input(UInt(64.W))
    }
    val halted    = Output(Bool())
    val exitCode  = Output(UInt(64.W))
    val fatal     = Output(Bool())
    val fatalPc   = Output(UInt(64.W))
    val fatalCode = Output(UInt(8.W))
    val dbg = Output(new Bundle {
      val gpr    = Vec(16, UInt(64.W))
      val xmm    = Vec(16, UInt(128.W))
      val flags  = UInt(64.W)
      val rip    = UInt(64.W)
      val cycles = UInt(64.W)
      val headSeq = UInt(32.W)
      val tailSeq = UInt(32.W)
      val iqUsed  = UInt(8.W)
      val canUse  = Bool()
      val dispatch = Bool()
      val issue    = Bool()
      val busyLow  = UInt(32.W)
      val iqReady  = UInt(8.W)
      val issuePc  = UInt(64.W)
      val issueRob = UInt(5.W)
      val iqInfo = Vec(8, UInt(32.W))
      val headValid = Bool()
      val headDone  = Bool()
      val headPc    = UInt(64.W)
      val headEntrySeq = UInt(32.W)
      val mqCountDbg = UInt(4.W)
      val mqHeadDbg  = UInt(3.W)
      val mqTailDbg  = UInt(3.W)
      val meValidDbg = Bool()
      val mePcDbg    = UInt(64.W)
      val meStoreDbg = Bool()
      val ldWaitDbg  = Bool()
      val stWaitDbg  = Bool()
      val sbMaskDbg  = UInt(8.W)
      val flushTargetDbg = UInt(64.W)
      val mqInfoDbg = Vec(8, UInt(64.W))
      val meOpDbg = UInt(8.W)
      val headSizeDbg = UInt(5.W)
      val meSizeDbg = UInt(5.W)
      val headDataLoDbg = UInt(64.W)
      val decOpDbg = UInt(8.W)
      val decAKindDbg = UInt(3.W)
      val decBKindDbg = UInt(3.W)
      val decMoveDbg = Bool()
      val decSizeDbg = UInt(5.W)
      val cr0Dbg = UInt(64.W)
      val cr3Dbg = UInt(64.W)
      val movCrWriteDbg = Bool()
      val movCrValDbg = UInt(64.W)
      val meVaddrDbg = UInt(64.W)
      val mePaddrDbg = UInt(64.W)
      val xlatDbg = UInt(4.W)
      val ptwDataDbg = UInt(64.W)
      val ptwValidDbg = Bool()
      val mmuFaultDbg = Bool()
      val ptwAddrDbg = UInt(64.W)
      val divOpDbg = UInt(8.W)
      val divADbg = UInt(64.W)
      val divBDbg = UInt(64.W)
      val divHiDbg = UInt(64.W)
      val divOpszDbg = UInt(5.W)
      val divErrDbg = Bool()
      val decIllegalDbg = Bool()
      val canDispatchDbg = Bool()
      val isCdqDbg = Bool()
      val issue2Cnt = UInt(32.W)
      val issue1Dbg = Bool()
      val meJmpMemDbg = Bool()
      val anyFwdDbg = Bool()
      val loadReqDbg = Bool()
      val meReadyDbg = Bool()
      val meComisDbg = Bool()
      val meHasDstFDbg = Bool()
      val mePdstFDbg = UInt(4.W)
      val decNeedFDbg = Bool()
      val decPdstFDbg = UInt(4.W)
      val ratFDbg = UInt(4.W)
      val f0Dbg = UInt(64.W)
      val f1Dbg = UInt(64.W)
      val f2Dbg = UInt(64.W)
      val f3Dbg = UInt(64.W)
    })
  })

  val core = Module(new OooCore)
  io.imem.req_valid := core.io.imem.valid
  io.imem.req_addr  := core.io.imem.req
  core.io.imem.respValid := io.imem.resp_valid
  core.io.imem.resp      := io.imem.resp_data

  io.dmem.req_valid := core.io.dmem.reqValid
  io.dmem.req_we    := core.io.dmem.reqWe
  io.dmem.req_addr  := core.io.dmem.reqAddr
  io.dmem.req_wdata := core.io.dmem.reqWdata
  io.dmem.req_wmask := core.io.dmem.reqWmask
  io.dmem.req_size  := core.io.dmem.reqSize
  core.io.dmem.respValid := io.dmem.resp_valid
  core.io.dmem.respData  := io.dmem.resp_data

  io.iptw.req_valid := core.io.iptw.reqValid
  io.iptw.req_addr  := core.io.iptw.reqAddr
  core.io.iptw.respValid := io.iptw.resp_valid
  core.io.iptw.respData  := io.iptw.resp_data

  io.ptw.req_valid := core.io.ptw.reqValid
  io.ptw.req_addr  := core.io.ptw.reqAddr
  core.io.ptw.respValid := io.ptw.resp_valid
  core.io.ptw.respData  := io.ptw.resp_data

  io.halted    := core.io.halted
  io.exitCode  := core.io.exitCode
  io.fatal     := core.io.fatal
  io.fatalPc   := core.io.fatalPc
  io.fatalCode := core.io.fatalCode
  io.dbg.gpr   := core.io.dbg.gpr
  io.dbg.flags := core.io.dbg.flags
  io.dbg.rip   := core.io.dbg.rip
  io.dbg.headSeq := core.io.dbg.headSeq
  io.dbg.tailSeq := core.io.dbg.tailSeq
  io.dbg.iqUsed := core.io.dbg.iqUsed
  io.dbg.canUse := core.io.dbg.canUse
  io.dbg.dispatch := core.io.dbg.dispatch
  io.dbg.issue := core.io.dbg.issue
  io.dbg.busyLow := core.io.dbg.busyLow
  io.dbg.iqReady := core.io.dbg.iqReady
  io.dbg.issuePc := core.io.dbg.issuePc
  io.dbg.issueRob := core.io.dbg.issueRob
  io.dbg.iqInfo := core.io.dbg.iqInfo
  io.dbg.headValid := core.io.dbg.headValid
  io.dbg.headDone := core.io.dbg.headDone
  io.dbg.headPc := core.io.dbg.headPc
  io.dbg.headEntrySeq := core.io.dbg.headEntrySeq
  io.dbg.mqCountDbg := core.io.dbg.mqCountDbg
  io.dbg.mqHeadDbg := core.io.dbg.mqHeadDbg
  io.dbg.mqTailDbg := core.io.dbg.mqTailDbg
  io.dbg.meValidDbg := core.io.dbg.meValidDbg
  io.dbg.mePcDbg := core.io.dbg.mePcDbg
  io.dbg.meStoreDbg := core.io.dbg.meStoreDbg
  io.dbg.ldWaitDbg := core.io.dbg.ldWaitDbg
  io.dbg.stWaitDbg := core.io.dbg.stWaitDbg
  io.dbg.sbMaskDbg := core.io.dbg.sbMaskDbg
  io.dbg.flushTargetDbg := core.io.dbg.flushTargetDbg
  io.dbg.mqInfoDbg := core.io.dbg.mqInfoDbg
  io.dbg.meOpDbg := core.io.dbg.meOpDbg
  io.dbg.headSizeDbg := core.io.dbg.headSizeDbg
  io.dbg.meSizeDbg := core.io.dbg.meSizeDbg
  io.dbg.headDataLoDbg := core.io.dbg.headDataLoDbg
  io.dbg.decOpDbg := core.io.dbg.decOpDbg
  io.dbg.decAKindDbg := core.io.dbg.decAKindDbg
  io.dbg.decBKindDbg := core.io.dbg.decBKindDbg
  io.dbg.decMoveDbg := core.io.dbg.decMoveDbg
  io.dbg.decSizeDbg := core.io.dbg.decSizeDbg
  io.dbg.cr0Dbg := core.io.dbg.cr0Dbg
  io.dbg.cr3Dbg := core.io.dbg.cr3Dbg
  io.dbg.movCrWriteDbg := core.io.dbg.movCrWriteDbg
  io.dbg.movCrValDbg := core.io.dbg.movCrValDbg
  io.dbg.meVaddrDbg := core.io.dbg.meVaddrDbg
  io.dbg.mePaddrDbg := core.io.dbg.mePaddrDbg
  io.dbg.xlatDbg := core.io.dbg.xlatDbg
  io.dbg.ptwDataDbg := core.io.dbg.ptwDataDbg
  io.dbg.ptwValidDbg := core.io.dbg.ptwValidDbg
  io.dbg.mmuFaultDbg := core.io.dbg.mmuFaultDbg
  io.dbg.ptwAddrDbg := core.io.dbg.ptwAddrDbg
  io.dbg.divOpDbg := core.io.dbg.divOpDbg
  io.dbg.divADbg := core.io.dbg.divADbg
  io.dbg.divBDbg := core.io.dbg.divBDbg
  io.dbg.divHiDbg := core.io.dbg.divHiDbg
  io.dbg.divOpszDbg := core.io.dbg.divOpszDbg
  io.dbg.divErrDbg := core.io.dbg.divErrDbg
  io.dbg.decIllegalDbg := core.io.dbg.decIllegalDbg
  io.dbg.canDispatchDbg := core.io.dbg.canDispatchDbg
  io.dbg.isCdqDbg := core.io.dbg.isCdqDbg
  io.dbg.issue2Cnt := core.io.dbg.issue2Cnt
  io.dbg.issue1Dbg := core.io.dbg.issue1Dbg
  io.dbg.meJmpMemDbg := core.io.dbg.meJmpMemDbg
  io.dbg.anyFwdDbg := core.io.dbg.anyFwdDbg
  io.dbg.loadReqDbg := core.io.dbg.loadReqDbg
  io.dbg.meReadyDbg := core.io.dbg.meReadyDbg
  io.dbg.meComisDbg := core.io.dbg.meComisDbg
  io.dbg.meHasDstFDbg := core.io.dbg.meHasDstFDbg
  io.dbg.mePdstFDbg := core.io.dbg.mePdstFDbg
  io.dbg.decNeedFDbg := core.io.dbg.decNeedFDbg
  io.dbg.decPdstFDbg := core.io.dbg.decPdstFDbg
  io.dbg.ratFDbg := core.io.dbg.ratFDbg
  io.dbg.f0Dbg := core.io.dbg.f0Dbg
  io.dbg.f1Dbg := core.io.dbg.f1Dbg
  io.dbg.f2Dbg := core.io.dbg.f2Dbg
  io.dbg.f3Dbg := core.io.dbg.f3Dbg
  io.dbg.cycles := core.io.dbg.cycles
  io.dbg.xmm := core.io.dbg.xmm
}
